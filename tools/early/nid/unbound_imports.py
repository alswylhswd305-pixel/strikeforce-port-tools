#!/usr/bin/env python3
"""List EBOOT imports that have no HLE handler in a ps3recomp build (Plan C tool, generalised).

  python unbound_imports.py <work_folder> [<ps3recomp_dir>]

Reads (all produced locally from YOUR own EBOOT, never committed):
  <work>/out/EBOOT.imports.json      from ps3recomp tools/ppu_loader.py
  <work>/port/bld/ppu_hle_nids.cpp   generated by the port's CMake configure
and scans <ps3recomp>/runtime + libs for extra registrations. Output: library, NID, name
(from ps3recomp tools/nid_from_protos.json when known, else '?'), import stub address.
Feed the '?' lines to tools/nid/nid.py resolve.
"""
import glob, json, os, re, sys
work = sys.argv[1] if len(sys.argv) > 1 else os.getcwd()
sdk = sys.argv[2] if len(sys.argv) > 2 else os.path.join(work, "ps3recomp")
imp = json.load(open(os.path.join(work, "out", "EBOOT.imports.json")))
reg = set(int(m, 16) for m in re.findall(r"ps3_hle_register\(\s*0x([0-9A-Fa-f]{8})",
          open(os.path.join(work, "port", "bld", "ppu_hle_nids.cpp")).read()))
txt = ""
for f in glob.glob(os.path.join(sdk, "runtime", "**", "*.c*"), recursive=True) + glob.glob(os.path.join(sdk, "libs", "**", "*.c*"), recursive=True):
    txt += open(f, errors="ignore").read()
for f in glob.glob(os.path.join(work, "port", "*.inc")) + glob.glob(os.path.join(work, "port", "*.cpp")):
    txt += open(f, errors="ignore").read()
extra = set(int(m, 16) for m in re.findall(r"(?:register|REG|NID)[^\n]{0,80}?0x([0-9A-Fa-f]{8})", txt))
names = {}
try:
    for k, v in json.load(open(os.path.join(sdk, "tools", "nid_from_protos.json"))).items():
        if isinstance(v, str) and v.startswith("0x"): names[int(v, 16)] = k
except Exception as e: print("protos:", e)
miss = []
for i in imp:
    n = int(i["nid"], 16)
    if n not in reg and n not in extra: miss.append((i["library"], "0x%08X" % n, names.get(n, "?"), i.get("stub", "?")))
print("imports", len(imp), "registered_in_table", sum(int(i["nid"], 16) in reg for i in imp), "missing", len(miss))
for m in sorted(miss): print("%-22s %s %-44s stub=%s" % m)
