LOW_CONFIDENCE_ARRAYS = {0x0A80, 0x1D00, 0x1900, 0x1940, 0x1980, 0x1480, 0x02C0, 0x02C4}


def public_name(m):
    """Return (name, confident) or (None, False)."""
    if m in SINGLE:
        return ("NV4097_" + SINGLE[m] if not SINGLE[m].startswith(("NV406E", "GCM_")) else SINGLE[m]), m not in LOW_CONFIDENCE
    for base, count, stride, name, lanes in ARRAYS:
        span = count * stride
        if base <= m < base + span:
            k, off = divmod(m - base, stride)
            if lanes:
                li = off // 4
                if li >= len(lanes):
                    continue
                lane = lanes[li]
                if name in ("SET_TEXTURE", "SET_VERTEX_TEXTURE"):
                    s = f"NV4097_{name}_{lane}" + (f"[{k}]" if count > 1 else "")
                else:
                    s = f"NV4097_{name}" + (f"[{k}]" if count > 1 else "") + f".{lane}"
                return s, base not in LOW_CONFIDENCE_ARRAYS
            if off % 4:
                continue
            return f"NV4097_{name}[{k + off // 4 if stride != 4 else k}]", base not in LOW_CONFIDENCE_ARRAYS
    return None, False
